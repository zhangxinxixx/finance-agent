const cmeText=cmeSandbox.module.exports.translateDecisionText('Model GEX is a Black-76/proxy estimate, not real dealer inventory.');
assert.match(cmeText,/代理估算.*不代表真实做市商库存/,'期权模型限制必须在词级替换之前完整翻译');
