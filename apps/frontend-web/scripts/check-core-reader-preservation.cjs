// Core independent acceptance: preserve concrete research judgment, JSON strategy fields and known direction enums; remove machine English and sources. Do not weaken assertions to fit implementation.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const root = process.argv[2] || path.resolve(__dirname, '../../..');
const filename = path.join(root, 'apps/frontend-web/src/lib/researchReading.ts');
const resultExports = {};
const sandbox = {exports:resultExports, module:{exports:resultExports}, console};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,sandbox,{filename});
const lib = sandbox.module.exports;
const sample = '# XAUUSD Strategy Card\n- version: 1.0\n- asset: XAUUSD\n- bias: neutral\n- confidence: 0.35\n- run_id: 12345678-1234-1234-1234-123456789012\n## Scenario Summary\nObserve and wait (fallback_failed_or_needs_review). No strong conclusion is permitted until QualityGate passes. 研究观察（不构成正式方向）：当前优先观察区间消化，综合方向尚未确认。官方 TIPS 实际利率 2.92%，变化 +4.0bp；须等待美元与现货的共同确认。\n## Risk Points\n- 宏观 前置风险：DXY directional change is unavailable; only the current level is confirmed.\n- 技术面输入不可用。\n- 期货执行价与 XAUUSD 现货不能直接等同。\n## Data Provenance\n- source_refs:\n- raw_path: raw/news/test.json; status: unavailable\n## Disclaimer\nResearch output only; not investment advice.';
const reading=lib.researchReading(sample);
const text=[...reading.highlights,...reading.remaining,...reading.risks].join('\n');
assert.match(text,/2\.92%/,'真实研究依据不得因同句有fallback前缀而丢失');
assert.match(text,/\+4\.0bp/,'保留原始关键变化');
assert.match(text,/美元|DXY/,'保留具体美元方向缺口');
assert.match(text,/现货/,'保留现货坐标限制');
assert.match(text,/尚未确认|暂不可|仅供观察|先观察/,'观察资格不能被清理为确定判断');
assert.match(reading.highlights.join('\n'),/当前优先观察区间|观察区间/,'默认重点必须保留研究判断，不能全部丢到风险或折叠区');
assert.doesNotMatch(text,/run_id|fallback_failed|QualityGate|raw_path|raw\/news/,'机器元数据不应进入正文');
assert.doesNotMatch(reading.highlights.join('\n'),/(?:^|\n)(?:version|asset|bias|confidence):/,'报告重点不得包含原始机器键值');
const duplicateRisks = [lib.readableWarning('宏观 前置风险：DXY directional change is unavailable; only the current level is confirmed.'),lib.readableWarning('风险 前置风险：Macro prior risk: DXY directional change is unavailable; only the current level is confirmed.')];
assert.equal(lib.uniqueReading(duplicateRisks).length,1,'不同模块转述的同一风险需要合并');
const long=lib.researchReading('# 当前判断\n'+ '观察区间，方向待确认。\n'.repeat(3000)+'## 风险\n美元方向缺失。\n现货数据不可用。\n');
assert(long.highlights.join('\n').length<8000,'重点阅读必须有界');
assert.match(long.risks.join('\n'),/美元方向缺失/,'后置重要风险仍保留');
const structured=lib.structuredResearch({scenario_summary:'观察区间，方向待确认。',risk_points:['美元方向缺失。'],invalid_conditions:['没有新鲜现货，不确认价格触发。'],source_refs:[{source_ref:'secret',raw_path:'raw/test',status:'unavailable'}]});
assert.match(structured,/观察区间/,'JSON策略卡必须能读出研究判断');
assert.match(structured,/美元方向缺失/,'JSON策略卡具体风险不得被泛化或丢失');
assert.match(structured,/新鲜现货/,'JSON策略卡保留失效条件');
assert.doesNotMatch(structured,/secret|raw\/test/,'JSON来源记录不得混入研究正文');
const warning = lib.readableWarning('This report is observe-only and must not replace an accepted final report.');
assert.match(warning,/观察|参考/,'观察报告限制必须用中文表达');
assert.doesNotMatch(warning,/observe-only|accepted final report/,'不得向用户展示机器英文警告');
const goldFile = path.join(root, 'apps/frontend-web/src/components/shared/goldMainlineFormat.ts');
const goldExports = {};
const goldSandbox = {exports:goldExports,module:{exports:goldExports},require:(name)=>name==='@/lib/researchReading'?lib:require(name),console};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(goldFile,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,goldSandbox,{filename:goldFile});
const narrative=goldSandbox.module.exports.formatGoldNarrativeText('美联储利率路径是当前主导因素，利多与利空并存，净影响为neutral_bearish。');
assert.match(narrative,/美联储利率路径/,'已知方向枚举不得导致整段研究判断消失');
assert.match(narrative,/中性偏空/,'已知方向应先翻译为中文，再清理机器记录');
const cmeFile = path.join(root, 'apps/frontend-web/src/components/cme-options/cmeOptionsFormat.ts');
const cmeExports = {};
const cmeSandbox = {exports:cmeExports,module:{exports:cmeExports},require:(name)=>name==='@/lib/researchReading'?lib:require(name),console};
